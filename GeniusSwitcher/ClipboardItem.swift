import Foundation

/// One entry of the clipboard history. The text of text entries is kept in memory (it is small and
/// search needs it); images, rich text and other data stay on disk in the entry's folder
/// (`ClipboardStore.directory/<id>/`) and are read only for the preview and for pasting.
struct ClipboardItem: Codable, Identifiable, Equatable {
    enum Kind: String, Codable {
        case text, image, files
    }

    var id: UUID
    /// When it was copied last (pasting from the history counts as copying it again).
    var date: Date
    var kind: Kind
    /// The app it was copied from.
    var app: String?
    /// Plain text: the whole text for text entries, file paths (one per line) for files.
    var text: String?
    /// Pasteboard types saved on disk, with their size in bytes ("public.rtf": 1520).
    var stored: [String: Int]
    /// Image size in pixels.
    var width: Int?
    var height: Int?
    /// Same content copied again moves the old entry to the top instead of adding a new one.
    var hash: String

    /// Bytes this entry takes on disk (plus its text, kept in the index).
    var bytes: Int { stored.values.reduce(0, +) + (text?.utf8.count ?? 0) }

    /// The line shown in the list.
    var title: String {
        switch kind {
        case .text:
            let trimmed = (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
            let firstLines = trimmed.prefix(300).split(whereSeparator: \.isNewline).joined(separator: " ⏎ ")
            return firstLines.isEmpty ? "(пробелы)" : String(firstLines)
        case .image:
            if let width, let height { return "Изображение \(width) × \(height)" }
            return "Изображение"
        case .files:
            let names = (text ?? "").split(separator: "\n").map { ($0 as NSString).lastPathComponent }
            return names.count > 1 ? "\(names[0]) и ещё \(names.count - 1)" : names.first ?? "Файл"
        }
    }
}

/// The pure rules of the history: what to keep, in which order and what to drop. Tested.
enum ClipboardRules {
    /// Never saved: password managers and apps that mark their copies as private or temporary
    /// (nspasteboard.org), plus Maccy's defaults.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "net.antelle.keeweb",
        "Pasteboard generator type", "com.typeit4me.clipping",
    ]

    /// Wallet seed phrases (12 or 24 lowercase words), as in Maccy's settings.
    static let seedPhrase = try! NSRegularExpression(
        pattern: #"\b(?:[a-z]{3,}\s+){11}[a-z]{3,}\b|\b(?:[a-z]{3,}\s+){23}[a-z]{3,}\b"#)

    /// Hard cap besides the size limit: the list stays quick to scroll.
    static let maxItems = 1000

    static func isSecret(_ text: String) -> Bool {
        seedPhrase.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)) != nil
    }

    /// Adds `item` on top. The same content copied before is replaced by it (its old folder must be
    /// deleted: returned in `removed`). Then the oldest entries go until the history fits `limit`
    /// bytes and `maxItems`; the newest entry stays even when it alone is over the limit.
    static func insert(_ item: ClipboardItem, into items: [ClipboardItem], limit: Int) -> (items: [ClipboardItem], removed: [ClipboardItem]) {
        var removed = items.filter { $0.hash == item.hash }
        var result = [item] + items.filter { $0.hash != item.hash }
        let trimmed = trim(result, limit: limit)
        result = trimmed.items
        removed += trimmed.removed
        return (result, removed)
    }

    static func trim(_ items: [ClipboardItem], limit: Int) -> (items: [ClipboardItem], removed: [ClipboardItem]) {
        var total = 0
        var kept: [ClipboardItem] = []
        var removed: [ClipboardItem] = []
        for item in items {
            total += item.bytes
            if kept.isEmpty || (total <= limit && kept.count < maxItems) {
                kept.append(item)
            } else {
                removed.append(item)
            }
        }
        return (kept, removed)
    }

    /// Search: every word of the query is somewhere in the entry, case-insensitive. A query typed
    /// in the wrong layout ("ghbdtn") also finds "привет": `alternative` is the query retyped in
    /// the other layout.
    static func matches(_ item: ClipboardItem, query: String, alternative: String?) -> Bool {
        let haystack = item.kind == .image ? item.title : (item.text ?? "")
        func all(_ query: String) -> Bool {
            let words = query.split(whereSeparator: \.isWhitespace)
            return !words.isEmpty && words.allSatisfy { haystack.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
        return all(query) || (alternative.map(all) ?? false)
    }

    /// `text` as if typed with the same keys in the other layout: "ghbdtn" → "привет", "руддщ" →
    /// "hello". Nil when it is not clearly in one of the two layouts.
    static func retyped(_ text: String, renderer: LayoutRendering) -> String? {
        let languages = renderer.languages
        guard languages.count == 2 else { return nil }
        var keysByLanguage: [String: [Character: TypedKey]] = [:]
        for language in languages {
            var map: [Character: TypedKey] = [:]
            for code in UInt16(0)..<UInt16(51) {
                for shift in [false, true] {
                    let key = TypedKey(code: code, shift: shift, caps: false)
                    if let char = renderer.character(key, language: language), map[char] == nil { map[char] = key }
                }
            }
            keysByLanguage[language] = map
        }
        // The layout the text was typed in: the one whose letters it uses.
        guard let from = languages.first(where: { language in
            text.contains { $0.isLetter } && text.allSatisfy { !$0.isLetter || keysByLanguage[language]?[$0] != nil }
        }), let to = renderer.other(than: from) else { return nil }
        var result = ""
        for char in text {
            if char.isWhitespace { result.append(char); continue }
            guard let key = keysByLanguage[from]?[char], let other = renderer.character(key, language: to) else { return nil }
            result.append(other)
        }
        return result == text ? nil : result
    }
}

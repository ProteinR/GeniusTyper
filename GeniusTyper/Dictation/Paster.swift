import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Inserts text into the app in front: puts it on the clipboard, posts ⌘V, then puts back what
/// the clipboard held. The text is marked transient (nspasteboard.org), so clipboard histories
/// (Genius Typer's) skip it. The text itself is handed over only when an app asks for it (a data
/// provider), and the old clipboard comes back 0.5 s after that, or after 5 s if nobody asked: a
/// fixed 0.6 s was too short for a busy app, which then pasted the old clipboard (2026-10-27).
@MainActor
enum Paster {
    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Shows the system prompt that leads to System Settings → Privacy → Accessibility.
    static func askForAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    /// False when it could not paste (no Accessibility): the text stays on the clipboard then.
    @discardableResult
    static func paste(_ text: String) -> Bool {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        let provider = Provider(text: text)
        // Without Accessibility the text stays for the user to paste: then it must be there itself.
        let trusted = isTrusted
        if trusted { item.setDataProvider(provider, forTypes: [.string]) } else { item.setString(text, forType: .string) }
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ours = pasteboard.changeCount

        guard trusted else {
            Log.warning("Cannot paste: Accessibility not granted; text left on the clipboard", "paste")
            return false
        }
        let source = CGEventSource(stateID: .combinedSessionState)
        // The dictation modifier may still be down (push-to-talk released a moment ago): only ⌘.
        let down = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)

        // Restore once the app has read the text (or nobody did), unless something else was
        // copied since.
        var restored = false
        let restore = {
            guard !restored else { return }
            restored = true
            provider.onRead = nil
            guard pasteboard.changeCount == ours else { return }
            pasteboard.clearContents()
            if !saved.isEmpty { pasteboard.writeObjects(saved) }
        }
        provider.onRead = {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { MainActor.assumeIsolated { restore() } }
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 5) {
            MainActor.assumeIsolated {
                if !restored { Log.warning("Paste: the text was not read within 5 s; clipboard restored", "paste") }
                restore()
            }
        }
        return true
    }

    /// Hands the text over when an app reads the clipboard and says so (the first read only).
    private final class Provider: NSObject, NSPasteboardItemDataProvider {
        let text: String
        var onRead: (() -> Void)?

        init(text: String) { self.text = text }

        func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
            item.setString(text, forType: type)
            let read = onRead
            onRead = nil
            read?()
        }
    }

    /// A copy of every item with all its types (text, RTF, images, files).
    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }
}
